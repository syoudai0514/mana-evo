/** その教科・学年の授業（無ければ 下の学年のものを さがす） */
export function lessonsFor(domainId, grade) {
  const byGrade = LESSONS[domainId]
  if (!byGrade) return []
  for (let g = grade; g >= 0; g--) {
    if (byGrade[g] && byGrade[g].length) return byGrade[g]
  }
  // 上の学年しか無い場合（低学年で理科など）は いちばん近いものを
  const keys = Object.keys(byGrade).map(Number).sort((a, b) => a - b)
  return keys.length ? byGrade[keys[0]] : []
}

/** 授業を1つ選ぶ（seed でだいたい固定できる） */
export function pickLesson(domainId, grade, seed = 0) {
  const list = lessonsFor(domainId, grade)
  if (!list.length) return null
  return list[Math.abs(seed) % list.length]
}

export function hasLesson(domainId, grade) {
  return lessonsFor(domainId, grade).length > 0
}
