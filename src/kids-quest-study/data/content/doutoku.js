function tierForGrade(grade) {
  if (grade <= 2) return 'low'
  if (grade <= 4) return 'mid'
  return 'high'
}

function poolForGrade(grade) {
  const tier = tierForGrade(grade)
  if (tier === 'low') return BANK.low
  if (tier === 'mid') return [...BANK.mid, ...BANK.low.slice(0, 3)]
  return [...BANK.high, ...BANK.mid.slice(0, 3)]
}

// 生命の終わりの話題は、保護者設定がONかつ現在の学年が高学年（5・6）の
// ときだけ候補に入れる。gradeMax ではなく grade で判定する
// （学年を戻した子には出ない ＝ 生成候補にすら入れない）。
function reflectPoolForGrade(grade, showLifeEndTopics) {
  const tier = tierForGrade(grade)
  if (tier === 'low') return []
  const pool = tier === 'mid' ? REFLECT_BANK.mid : [...REFLECT_BANK.high, ...REFLECT_BANK.mid]
  const allowLifeEnd = showLifeEndTopics === true && grade >= 5
  return pool.filter((item) => !item.lifeEnd || allowLifeEnd)
}

function build(item, cc) {
  // 正解だけが長いという見た目の手掛かりを消すため、最長の誤答は必ず含める。
  const longestWrong = [...item.d].sort((a, b) => b.length - a.length)[0]
  const otherWrong = shuffle(item.d.filter((value) => value !== longestWrong)).slice(0, Math.max(1, cc - 2))
  const opts = shuffle([item.a, longestWrong, ...otherWrong])
  return {
    domain: 'doutoku',
    type: 'choice',
    itemKey: `d:${item.q}`,
    visual: { kind: 'bigtext', text: '💗' },
    instruction: item.q,
    speak: item.q,
    answerId: item.a,
    choices: opts.map((v) => ({ id: v, label: v, speak: v })),
    answerWord: { text: item.a },
    explain: item.e
  }
}

