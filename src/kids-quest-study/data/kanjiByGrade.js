export function jukugoPoolForGrade(grade) {
  if (grade <= 0) return []
  const cur = JUKUGO_BY_GRADE[grade] || JUKUGO_BY_GRADE[6]
  const prev = grade >= 2 ? (JUKUGO_BY_GRADE[grade - 1] || []).slice(0, 8) : []
  return [...cur, ...prev]
}

