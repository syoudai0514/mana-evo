// 年長は小1のかんたんな漢字（数字・自然・からだ）だけ
export const GRADE0_KANJI_COUNT = 48

export function kanjiPoolForGrade(grade) {
  if (grade <= 0) return KANJI_BY_GRADE[1].slice(0, GRADE0_KANJI_COUNT)
  // その学年 + 前の学年を少し混ぜる（復習）
  const cur = KANJI_BY_GRADE[grade] || KANJI_BY_GRADE[6]
  const prev = grade >= 2 ? (KANJI_BY_GRADE[grade - 1] || []).slice(0, 12) : []
  return [...cur, ...prev]
}

