#!/usr/bin/env node
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const MONSTER_DIR = path.join(ROOT, 'public', 'monsters')
const PROVENANCE_DIR = path.join(ROOT, 'design', 'rebuild', 'asset-production', 'candidate-provenance')
const OUT = path.join(ROOT, 'src', 'game', 'candidateArt.generated.js')

const speciesIdFrom = (name, ext) => {
  const match = new RegExp(`^(m\\d{3})\\.${ext}$`).exec(name)
  if (!match) return null
  const no = Number(match[1].slice(1))
  return no >= 1 && no <= 238 ? match[1] : null
}

const sha256 = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex')
const sorted = (values) => [...values].sort((a, b) => Number(a.slice(1)) - Number(b.slice(1)))

function failSet(label, left, right) {
  const missing = sorted([...left].filter((id) => !right.has(id)))
  if (missing.length) throw new Error(`${label}: ${missing.join(', ')}`)
}

function validateCandidate(speciesId) {
  const assetPath = path.join(MONSTER_DIR, `${speciesId}.webp`)
  const provenancePath = path.join(PROVENANCE_DIR, `${speciesId}.json`)
  const bytes = fs.readFileSync(assetPath)
  const provenance = JSON.parse(fs.readFileSync(provenancePath, 'utf8'))
  if (provenance.speciesId !== speciesId || !Array.isArray(provenance.events) || provenance.events.length === 0) {
    throw new Error(`Malformed provenance for ${speciesId}`)
  }
  const latest = provenance.events.at(-1)
  if (latest?.candidate?.repositoryPath !== `public/monsters/${speciesId}.webp`) {
    throw new Error(`Candidate path mismatch for ${speciesId}`)
  }
  if (latest.formalPromotion !== false) throw new Error(`Candidate registry cannot include FORMAL promotion event for ${speciesId}`)
  if (latest.candidate.bytes !== bytes.length) throw new Error(`Candidate byte count mismatch for ${speciesId}`)
  if (latest.candidate.sha256 !== sha256(bytes)) throw new Error(`Candidate SHA-256 mismatch for ${speciesId}`)
  return {
    speciesId,
    src: `/monsters/${speciesId}.webp`,
    sha256: latest.candidate.sha256,
    bytes: latest.candidate.bytes,
  }
}

const assetIds = new Set(fs.readdirSync(MONSTER_DIR).map((name) => speciesIdFrom(name, 'webp')).filter(Boolean))
const provenanceIds = new Set(fs.readdirSync(PROVENANCE_DIR).map((name) => speciesIdFrom(name, 'json')).filter(Boolean))
failSet('WebP without candidate provenance', assetIds, provenanceIds)
failSet('Candidate provenance without WebP', provenanceIds, assetIds)

const candidates = sorted(assetIds).map(validateCandidate)
const generated = `// GENERATED by scripts/monster-art/generate-candidate-index.mjs. Do not hand edit.\n` +
  `// Source of truth: current public/monsters/mNNN.webp + candidate-provenance/mNNN.json.\n` +
  `export const CANDIDATE_ART_SPECIES = Object.freeze(${JSON.stringify(candidates.map(({ speciesId }) => speciesId), null, 2)})\n` +
  `export const CANDIDATE_ART_METADATA = Object.freeze(${JSON.stringify(Object.fromEntries(candidates.map((entry) => [entry.speciesId, entry])), null, 2)})\n`

fs.writeFileSync(OUT, generated)
console.log(`candidate art registry: ${candidates.length} species -> ${path.relative(ROOT, OUT)}`)
