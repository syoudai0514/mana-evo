// ===== 3. rank軸の分離 =====
w('## 3. rank・野生出現・一回限定を別の軸にする')
w()
w('rank=legend（13体）には、通常の3段階系列の最終進化形')
w('（進化すれば何度でも入手できる）が9体含まれるため、「legend=固定の1回きり」と')
w('説明しない。')
w()
w('rank は **捕獲のしにくさだけ**の軸として使い、以下は系列の形から別に判定する。')
w()
w('| 軸 | 値 | 判定方法 |')
w('|---|---|---|')
w('| rank | ふつう／めずらしい／とてもめずらしい／でんせつ | データで直接指定（捕獲式の rate に使う） |')
w('| pool（出会い方） | wild／evolutionOnly／event | 系列内の位置（第1〜中間形態＝wild／最終形態＝evolutionOnly／単体系列＝event）から自動判定 |')
w('| repeat（何度でも入手できるか） | unlimited／once | pool=event（単体系列）だけが once |')
w('| bossGated | true／false | pool=event（単体系列）だけが true |')
w()
{
  const counts = { wild: 0, evolutionOnly: 0, event: 0 }
  const legendNonEvent = []
  FAMILIES.forEach((f) => f.members.forEach((m, i) => {
    const info = encounterInfo(f, i + 1)
    counts[info.pool]++
    if (m.rank === 'legend' && info.pool !== 'event') legendNonEvent.push(m.name)
  }))
  w(`実データでの内訳: wild ${counts.wild}体 / evolutionOnly ${counts.evolutionOnly}体 / event ${counts.event}体`)
  w()
  w(`rank=legend（13体）のうち、実際に一回限定なのは ${13 - legendNonEvent.length}体だけ。`)
  w(`残り${legendNonEvent.length}体（${legendNonEvent.join('、')}）は、進化すれば何度でも入手できる`)
  w('（evolutionOnly＝最終形態のため野生には出ないが、捕獲→育成→進化で誰でも到達できる）。')
}
w()
w('この分離により、「legend=激レア」という直感は保ったまま、')
w('「でも進化で手に入る子はちゃんと手に入る」を両立できる。')
w()
w('---')
