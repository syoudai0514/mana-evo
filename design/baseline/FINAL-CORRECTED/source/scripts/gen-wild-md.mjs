// ===== 1. 捕獲の数式 =====
w('## 1. 捕獲の数式（方式Aのみ）')
w()
w('```')
w('a = min(255, rate × ball倍率)')
w('P（1投） = (a / 255)^(3/4)')
w('P（3投累積） = 1 − (1 − P)^3')
w('```')
w()
w('この簡約形は、参考にした旧来式の4段階サブ判定と同じ最終成功確率になる')
w('（a = 10/45/90/135/180/200/254 の7点で元式と検算済み）。**ここで述べているのは確率計算の由来のみで、視覚演出の仕様ではない。**')
w()
w('旧方式Bで使っていたHP残量の補正項')
w('（`(3×HPmax − 2×HPcur) / (3×HPmax)`）は「戦闘中に捕獲する」方式用であり、本作では使わない。')
w('方式Aでは捕獲フェーズに入る時点で敵は必ずHP0（たおしている）なので、HP項は意味を持たない。撤廃した。')
w()
w('| ランク | rate | ほしのわ×1 | ぎんのわ×1.5 | きんのわ×2 | にじのわ |')
w('|---|---|---|---|---|---|')
for (const [rankKey, rate] of Object.entries(RATE)) {
  const row = ['star', 'silver', 'gold', 'rainbow'].map((bk) => {
    const p1 = singleThrowRate(rate, bk)
    return `1投${(p1 * 100).toFixed(0)}%`
  })
  w(`| ${RANK_LABEL[rankKey]} | ${rate} | ${row.join(' | ')} |`)
}
w()
w('### 3投累積（誇張表現の禁止）')
w()
w('> ふつう×ほしのわでも厳密な100%ではない。')
w('> 1投成功率は83.34%、3投累積は**約99.54%**。したがって「かならず」と表示しない。')
w()
w('| ランク | ほしのわ 3投累積 | ぎんのわ 3投累積 | きんのわ 3投累積 | にじのわ |')
w('|---|---|---|---|---|')
for (const [rankKey, rate] of Object.entries(RATE)) {
  const row = ['star', 'silver', 'gold', 'rainbow'].map((bk) => {
    const p3 = cumulativeRate(rate, bk)
    return `${(p3 * 100).toFixed(2)}%`
  })
  w(`| ${RANK_LABEL[rankKey]} | ${row.join(' | ')} |`)
}
w()
w('**「かならずつかまる」「100%」と言えるのは にじのわ だけ。** それ以外は画面でも')
w('「ほとんど つかまる」「つかまえやすい」「つかまえにくい」のような相対表現にとどめ、')
w('数字を見せる場合も小数点まで正直に出す（丸めて100%と表示しない）。')
w()
w('### 表示ラベル（UIでの見せ方）')
w()
w('| 3投累積 | 表示 | ★の目安 |')
w('|---|---|---|')
for (const p of [0.99, 0.85, 0.6, 0.3, 0.1]) {
  w(`| ${(p*100).toFixed(0)}% | ${displayLabel(p)} | ${starRating(p)} |`)
}
w()
w('### 視覚演出（確率計算とは分離）')
w()
w('- 画面上の主役は**4つの星が順に点灯して輪が完成する**こと。')
w('- 成功時は4つ点灯後に輪が虹色に閉じる。')
w('- 失敗時は途中まで点灯した星が散り、輪がほどける。')
w('- 「わ」が4回物理的に揺れることは必須仕様にしない。')
w('- 内部で段階的なサブ判定を用いる場合でも、それをそのまま物理アニメーション回数へ結びつけない。')
w('- UI詳細は `03-screens-catch-and-raise.md`、横断原則は `08-gameplay-state-spec.md` §10 を優先する。')
w()
w('---')
w()

// ===== 2. 救済しない方針 =====
w('## 2. 捕獲の救済は入れない')
w()
w('「3回逃げられたら次は必ず成功」のような隠し救済は入れない。')
w('低確率で3投とも失敗すること自体は、')
